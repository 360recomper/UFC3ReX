// ufc3 - opt-in 60 fps for walkouts, intros and replays (--ufc3_cutscene_60).
//
// The game keeps its frame rate in a global at 0x833C80B8:
//   +0x08 fps (60/50/30/25), +0x0C lock flag, +0x1C fps as float, +0x20 ms per
//   frame, +0x24 ms (int), +0x38 60 Hz ticks per frame (1.0, 2.0 at 30) and
//   +0x3C its inverse (1.0, 0.5 at 30).
// sub_82748C20(fps) sets it from the config at boot; sub_82748D38 halves it
// (60 -> 30, 50 -> 25) and sub_82748DC8 restores it. About 30 call sites halve
// the rate when a walkout, intro, replay or other heavy scene starts. The
// render loop (sub_8273BBE0) notices the change and calls the D3D
// present-interval setter (sub_82376BB8, device+13872) with 2 for 30/25 fps, so
// the swap interrupt (sub_8237B6D0) holds each flip for two vblanks: exactly
// 33.33 ms.
//
// Skipping the halving keeps fps and the frame-time values at 60 together.
// Most code scales by +0x38 and is fine at 60, but the fighter in the walkout
// still steps at the 30 fps rate (2x speed, then waits for the music/camera
// timeline). --ufc3_cs60_trace counts calls to candidate stepping functions
// (cs60_trace.h, generated by tools/gen_cs60_trace.py) per halved/normal period
// to find that code.

#pragma once

#include <algorithm>
#include <atomic>
#include <chrono>
#include <mutex>
#include <string>
#include <utility>
#include <vector>

#include <rex/cvar.h>
#include <rex/logging.h>
#include <rex/ppc/func.h>

#include "no_bloom.h"
#include "no_dof.h"

REXCVAR_DEFINE_BOOL(ufc3_cutscene_60, false, "ufc3",
                    "Keep walkouts, intros and replays at 60 fps (the game drops them to 30)");
REXCVAR_DEFINE_BOOL(ufc3_cs60_trace, false, "ufc3",
                    "Log call counts of candidate 30 fps stepping functions per scene");

#include "cs60_trace.h"

REX_EXTERN(__imp__sub_82748D38);  // frame-rate global: halve 60 -> 30, 50 -> 25
REX_EXTERN(__imp__sub_82748DC8);  // frame-rate global: restore 30 -> 60, 25 -> 50
REX_EXTERN(__imp__sub_8273BBE0);  // render loop: present once per frame

namespace ufc3_cs60 {

inline std::mutex g_mutex;
inline bool g_halved = false;  // a halve was requested and not restored yet
inline auto g_period_start = std::chrono::steady_clock::now();

// Logs the calls counted since the last dump, highest first, and resets them.
inline void DumpLocked(const char* why) {
  using namespace ufc3_cs60_trace;
  auto now = std::chrono::steady_clock::now();
  double secs = std::chrono::duration<double>(now - g_period_start).count();
  g_period_start = now;
  std::vector<std::pair<uint32_t, uint32_t>> hits;
  for (int i = 0; i < kCount; ++i) {
    uint32_t n = g_calls[i].exchange(0, std::memory_order_relaxed);
    if (n) hits.emplace_back(n, kAddr[i]);
  }
  std::sort(hits.rbegin(), hits.rend());
  std::string line;
  for (auto& [n, addr] : hits) line += fmt::format(" {:08X}={}", addr, n);
  REXLOG_INFO("[cs60trace] {} state={} secs={:.1f}{}", why, g_halved ? "halved" : "normal", secs,
              line);
}

inline void SetHalved(bool halved, uint32_t lr) {
  if (!REXCVAR_GET(ufc3_cs60_trace)) {
    g_halved = halved;
    return;
  }
  std::lock_guard<std::mutex> lock(g_mutex);
  if (g_halved == halved) return;
  // Periods under half a second are merged into the next one (no dump), so a
  // halve/restore pair every frame cannot flood the log.
  static uint32_t switches = 0;
  if (std::chrono::steady_clock::now() - g_period_start >= std::chrono::milliseconds(500)) {
    DumpLocked(halved ? "halve" : "restore");
  }
  g_halved = halved;
  if (++switches <= 200) {
    REXLOG_INFO("[cs60trace] now {} (from {:08X})", halved ? "halved" : "normal", lr);
  }
}

}  // namespace ufc3_cs60

extern "C" REX_FUNC(sub_82748D38) {
  ufc3_cs60::SetHalved(true, ctx.lr);
  if (!REXCVAR_GET(ufc3_cutscene_60)) {
    __imp__sub_82748D38(ctx, base);
    return;
  }
  static std::atomic<uint32_t> skipped{0};
  uint32_t n = ++skipped;
  if (n <= 20 || n % 100 == 0) {
    REXLOG_INFO("[cutscene60] kept 60 fps (halve call #{} from {:08X})", n, ctx.lr);
  }
}

extern "C" REX_FUNC(sub_82748DC8) {
  ufc3_cs60::SetHalved(false, ctx.lr);
  __imp__sub_82748DC8(ctx, base);
}

extern "C" REX_FUNC(sub_8273BBE0) {
  ufc3_shader_patch::Tick(base);
  if (REXCVAR_GET(ufc3_cs60_trace)) {
    std::lock_guard<std::mutex> lock(ufc3_cs60::g_mutex);
    if (std::chrono::steady_clock::now() - ufc3_cs60::g_period_start >= std::chrono::seconds(10)) {
      ufc3_cs60::DumpLocked("tick");
    }
  }
  __imp__sub_8273BBE0(ctx, base);
}
